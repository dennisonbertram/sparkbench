// The "Advanced" gallery examples run hand-written firmware (src/core/firmware.ts) on the
// planner's circuit. Each must actually do its job in simulation.
import { describe, it, expect } from 'vitest';
import { buildExample } from '../../src/core/examples';
import { simulate, type ScriptedInput } from '../../src/sim/node-runner';
import type { Project } from '../../src/core/types';
import type { EPaperDevice } from '../../src/sim/devices';

const idOf = (p: Project, type: string, n = 0) => p.parts.filter((x) => x.type === type)[n].id;
const at = (snaps: { atMs: number; frame: any }[], ms: number) => snaps.find((s) => s.atMs === ms)!.frame;
const press = (part: string, atMs: number, holdMs = 200): ScriptedInput[] => [
  { atMs, part, key: 'pressed', value: 1 },
  { atMs: atMs + holdMs, part, key: 'pressed', value: 0 },
];
const lcdText = (frame: any, id: string) => {
  const s = String.fromCharCode(...frame.parts[id].lcd.chars);
  return [s.slice(0, 16), s.slice(16)];
};

/** Build an example, optionally patching a setting in its main.py. */
function build(id: string, patch?: [string, string]) {
  const p = buildExample(id);
  if (patch) {
    expect(p.files['main.py']).toContain(patch[0]);
    p.files['main.py'] = p.files['main.py'].replace(patch[0], patch[1]);
  }
  return p;
}

async function run(p: Project, untilMs: number, inputs: ScriptedInput[] = [], frames: number[] = []) {
  const r = await simulate(p, { untilMs, inputs, onFrameAt: frames });
  if (r.engine.error) console.log(r.engine.error.raw);
  expect(r.engine.error).toBeUndefined();
  expect(r.engine.allWarnings.filter((w) => w.severity === 'error')).toEqual([]);
  return { ...r, log: r.engine.serialAll.join('\n') };
}

describe('advanced examples', { timeout: 60000 }, () => {
  it('uses hand-written firmware on the planned circuit', () => {
    for (const id of ['esp32-eink-weather', 'esp32-internet-clock', 'pico-simon', 'esp32-pedometer', 'rpi-weather-dashboard']) {
      const p = buildExample(id);
      expect(p.codeCustom).toBe(true);
      expect(p.files['main.py']).not.toMatch(/Generated by Sparkbench/);
    }
    // driver files are still shipped next to main.py
    expect(Object.keys(buildExample('esp32-eink-weather').files)).toContain('epaper2in9.py');
    expect(Object.keys(buildExample('pico-simon').files)).toContain('ssd1306.py');
    expect(Object.keys(buildExample('rpi-weather-dashboard').files)).toContain('oled.py');
  });

  // ---------------------------------------------------------------- e-ink weather station
  it('e-ink weather station draws the forecast and rate-limits refreshes', async () => {
    const p = build('esp32-eink-weather');
    const btn = idOf(p, 'pushbutton');
    const epdId = idOf(p, 'epaper29');
    const { engine, snapshots, log } = await run(p, 72000, press(btn, 20000), [15000, 55000, 71000]);
    expect(log).toMatch(/Wi-Fi connected/);
    expect(log).toMatch(/Clock set from the internet/);
    expect(log).toMatch(/Now 14\.6 C Cloudy, high 17 \/ low 9/);
    expect(log).toMatch(/Forecast: Tue 17\/9 Cloudy \| Wed 15\/9 Light rain \| Thu 20\/11 Mostly clear/);
    expect(log).toMatch(/Indoor 22\.5 C 45 %/);
    // one refresh after boot; the button press at 20 s is queued until a minute has passed
    expect(at(snapshots, 15000).parts[epdId].epaper.refreshes).toBe(1);
    expect(log).toMatch(/update queued/);
    expect(at(snapshots, 55000).parts[epdId].epaper.refreshes).toBe(1);
    expect(at(snapshots, 71000).parts[epdId].epaper.refreshes).toBe(2);
    expect((log.match(/open-meteo\.com.*→ 200/g) ?? []).length).toBe(2);
    const epd = (engine as any).epapers[0].dev as EPaperDevice;
    const px = epd.pixels();
    const ink = (x0: number, y0: number, x1: number, y1: number) => {
      let n = 0;
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) n += px[y * 296 + x];
      return n;
    };
    expect(ink(6, 6, 54, 54)).toBeGreaterThan(80); // the weather icon
    expect(ink(64, 8, 160, 40)).toBeGreaterThan(300); // big temperature digits
    expect(ink(0, 66, 296, 67)).toBeGreaterThan(250); // divider above the forecast strip
    for (let i = 0; i < 3; i++) expect(ink(i * 98 + 6, 70, i * 98 + 96, 110)).toBeGreaterThan(60); // 3 forecast columns
  });

  it('e-ink weather station shows a message instead of crashing without Wi-Fi', async () => {
    const p = build('esp32-eink-weather');
    const board = idOf(p, 'esp32-devkit');
    const { engine, log } = await run(p, 15000, [{ atMs: 0, part: board, key: 'wifi', value: 0 }]);
    expect(log).toMatch(/Wi-Fi NOT connected/);
    const epd = (engine as any).epapers[0].dev as EPaperDevice;
    expect(epd.refreshes).toBe(1);
    expect(epd.pixels().some((b) => b)).toBe(true);
  });

  // ---------------------------------------------------------------- internet alarm clock
  it('internet clock shows NTP time with the UTC offset, date and temperature', async () => {
    const p = build('esp32-internet-clock');
    const lcd = idOf(p, 'lcd1602');
    const { snapshots, log } = await run(p, 6000, [], [5500]);
    expect(log).toMatch(/Time set from the internet/);
    // NTP sample time is 2026-10-20 10:30 UTC; UTC_OFFSET_H = -4
    const [l1, l2] = lcdText(at(snapshots, 5500), lcd);
    expect(l1).toMatch(/^06:30:0\d {2}20 Oct$/);
    expect(l2).toMatch(/^22\.5C 45%\s+\*07:00$/);
  });

  it('internet clock: the alarm rings, snoozes for 5 minutes and rings again', async () => {
    const p = build('esp32-internet-clock', ['ALARM_TIME = (7, 0)', 'ALARM_TIME = (6, 30)']);
    const lcd = idOf(p, 'lcd1602');
    const bz = idOf(p, 'buzzer');
    const snooze = idOf(p, 'pushbutton', 0);
    const ringing = Array.from({ length: 20 }, (_, i) => 2500 + i * 50);
    const { snapshots, log } = await run(p, 307000, press(snooze, 4000), [...ringing, 5000, 6500]);
    expect(Math.max(...ringing.map((ms) => at(snapshots, ms).parts[bz].tone ?? 0))).toBe(2400);
    expect(lcdText(at(snapshots, 3000), lcd)[1]).toMatch(/WAKE UP|^\s*$/);
    expect(at(snapshots, 5000).parts[bz].tone ?? 0).toBe(0);
    expect(log).toMatch(/Snooze 5 min/);
    expect(lcdText(at(snapshots, 6500), lcd)[1]).toMatch(/z06:35$/);
    expect((log.match(/ALARM! Wake up!/g) ?? []).length).toBe(2); // again after the snooze
  });

  it('internet clock: button B switches the alarm off', async () => {
    const p = build('esp32-internet-clock', ['ALARM_TIME = (7, 0)', 'ALARM_TIME = (6, 30)']);
    const lcd = idOf(p, 'lcd1602');
    const bz = idOf(p, 'buzzer');
    const onOff = idOf(p, 'pushbutton', 1);
    const late = Array.from({ length: 20 }, (_, i) => 7000 + i * 50);
    const { snapshots, log } = await run(p, 8500, press(onOff, 4000), [4500, ...late, 8000]);
    expect(log).toMatch(/Alarm OFF/);
    expect(lcdText(at(snapshots, 4500), lcd)[1]).toMatch(/Alarm OFF/);
    expect(lcdText(at(snapshots, 8000), lcd)[1]).toMatch(/ off$/);
    expect(late.every((ms) => (at(snapshots, ms).parts[bz].tone ?? 0) === 0)).toBe(true);
  });

  // ---------------------------------------------------------------- Simon
  it('Simon: matching the sequence advances a level, a wrong colour ends the game', async () => {
    const start = (p: Project) => press(idOf(p, 'pushbutton', 0), 500, 100);
    const buttonFor = (p: Project, colour: string) => p.parts.find((x) => x.type === 'pushbutton' && x.props.color === colour)!.id;
    const ledFor = (p: Project, colour: string) => p.parts.find((x) => x.type === 'led' && x.props.color === colour)!.id;

    // Pass 1: start a game and read the first colour (the seed depends only on when the start
    // button was pressed, so the same script gives the same sequence).
    const p1 = build('pico-simon');
    const r1 = await run(p1, 3000, start(p1), [2100]);
    const first = /\[debug\] sequence: (\w+)/.exec(r1.log)![1];
    expect(['red', 'green', 'blue', 'yellow']).toContain(first);
    // ...and Simon really shows it: only that LED is lit while it plays
    const lit = ['red', 'green', 'blue', 'yellow'].filter((c) => (at(r1.snapshots, 2100).parts[ledFor(p1, c)].led ?? 0) > 0.2);
    expect(lit).toEqual([first]);
    expect(r1.log).toMatch(/Your turn/);

    // Pass 2: repeat it correctly, then get level 2 wrong on purpose.
    const p2 = build('pico-simon');
    const wrong = ['red', 'green', 'blue', 'yellow'].find((c) => c !== first)!;
    const r2 = await run(p2, 10000, [...start(p2), ...press(buttonFor(p2, first), 3000), ...press(buttonFor(p2, wrong), 7000)], [3100]);
    expect(at(r2.snapshots, 3100).parts[ledFor(p2, first)].led).toBeGreaterThan(0.2); // the press lights its own colour
    expect(r2.log).toMatch(/Correct!/);
    expect(r2.log).toMatch(/Level 2/);
    expect(r2.log).toMatch(new RegExp(`\\[debug\\] sequence: ${first} \\w+`));
    expect(r2.log).toMatch(/Game over: Wrong colour! - score 1/);
    const oled = (r2.engine as any).devices.find((d: any) => d.part.type === 'ssd1306').dev;
    expect(oled.ram.some((b: number) => b)).toBe(true);
  });

  // ---------------------------------------------------------------- step counter
  it('step counter counts ~1.8 steps/s while walking and nothing when still', async () => {
    const p = build('esp32-pedometer');
    const imu = idOf(p, 'mpu6050');
    const btn = idOf(p, 'pushbutton');
    const inputs: ScriptedInput[] = [{ atMs: 2000, part: imu, key: 'walking', value: 1 }, { atMs: 12000, part: imu, key: 'walking', value: 0 }, ...press(btn, 24000)];
    const { log } = await run(p, 26000, inputs);
    const counts = [...log.matchAll(/Steps (\d+) \| (\d+) spm/g)].map((m) => [Number(m[1]), Number(m[2])]);
    const stepsAt = (s: number) => counts[s - 1][0]; // one log line per second
    expect(stepsAt(2)).toBe(0); // standing still: nothing counted
    const walked = stepsAt(14);
    expect(walked).toBeGreaterThanOrEqual(18 * 0.8); // 10 s × 1.8 steps/s = 18 (±20 %)
    expect(walked).toBeLessThanOrEqual(18 * 1.2);
    expect(stepsAt(23)).toBe(walked); // stopped again: the count holds
    expect(Math.max(...counts.map((c) => c[1]))).toBeGreaterThan(95); // cadence ≈ 108 spm
    expect(counts[counts.length - 1][0]).toBe(0); // button reset
    expect(log).toMatch(/Reset/);
  });

  // ---------------------------------------------------------------- Raspberry Pi dashboard
  it('Pi weather dashboard shows pages, flips with the button, rain LED follows today', async () => {
    const p = build('rpi-weather-dashboard');
    const btn = idOf(p, 'pushbutton');
    const led = idOf(p, 'led');
    const oledId = idOf(p, 'ssd1306');
    const { snapshots, log } = await run(p, 6000, [...press(btn, 3000), ...press(btn, 4500)], [2500, 4000, 5500]);
    expect(log).toMatch(/Now 14\.6 C Cloudy \| today 17\/9 C, rain 20%/);
    expect(log).toMatch(/Next days: Tue 17\/9 20% \| Wed 15\/9 80% \| Thu 20\/11 5%/);
    // sample data: 20 % rain today < 50 % → no warning
    expect(at(snapshots, 2500).parts[led].led ?? 0).toBeLessThan(0.05);
    expect(log).toMatch(/Rain warning LED off \(20% today\)/);
    expect(log).toMatch(/Page 2\/3: TODAY/);
    expect(log).toMatch(/Page 3\/3: 3 DAYS/);
    const screens = [2500, 4000, 5500].map((ms) => JSON.stringify(at(snapshots, ms).parts[oledId].oled));
    expect(new Set(screens).size).toBe(3);
    expect(at(snapshots, 5500).parts[oledId].oled.some((b: number) => b)).toBe(true);
  });

  it('Pi weather dashboard lights the rain LED when the threshold is reached', async () => {
    const p = build('rpi-weather-dashboard', ['RAIN_WARN_PCT = 50', 'RAIN_WARN_PCT = 20']);
    const led = idOf(p, 'led');
    const { snapshots, log } = await run(p, 3000, [], [2500]);
    expect(log).toMatch(/Rain warning LED ON/);
    expect(at(snapshots, 2500).parts[led].led).toBeGreaterThan(0.2);
  });
});
