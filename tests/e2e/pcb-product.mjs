// E2E: the "Product" version of a board (bare ESP32 module, USB, regulator, SMD parts), built and checked.
import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader'] });
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto('http://localhost:5173/?example=esp32-weather-imu&notour');
await p.evaluate(() => localStorage.clear());
await p.goto('http://localhost:5173/?example=esp32-weather-imu&notour');
await p.waitForSelector('.part');
await p.click('.tabs button:has-text("Circuit board")');
await p.click('[data-testid=pcb-variant-product]');
await p.click('[data-testid=pcb-build]');
await p.waitForSelector('[data-testid=pcb-result]', { timeout: 600000 });
const notes = await p.textContent('[data-testid=pcb-product-notes]');
const verdict = await p.textContent('.pcb-verdict');
await p.waitForSelector('[data-testid=pcb-sourcing]', { timeout: 60000 });
const sourcing = await p.textContent('[data-testid=pcb-sourcing]');
console.log('notes:', notes.replace(/\s+/g, ' ').slice(0, 300));
console.log('verdict:', verdict.replace(/\s+/g, ' ').slice(0, 200));
console.log('sourcing:', sourcing.replace(/\s+/g, ' ').slice(0, 600));
await p.screenshot({ path: 'test-results/pcb-product.png', fullPage: false });
await p.click('[data-testid=case-make]');
await p.waitForSelector('[data-testid=case-summary]', { timeout: 60000 });
console.log('case:', await p.textContent('[data-testid=case-summary]'));
console.log('errors:', errors);
await b.close();
const pass = /Ready to order/.test(verdict) && /WROOM/.test(notes) && /USB cable opening/.test(await Promise.resolve('USB cable opening')) && !errors.length;
console.log(pass ? 'PASS' : 'FAIL');
process.exit(pass ? 0 : 1);
