// E2E: arrange a part by hand on the circuit board, re-route, and check the board is still clean.
import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto('http://localhost:5173/?example=pico-traffic-light&notour');
await p.evaluate(() => localStorage.clear());
await p.goto('http://localhost:5173/?example=pico-traffic-light&notour');
await p.waitForSelector('.part');
await p.click('.tabs button:has-text("Circuit board")');
await p.click('[data-testid=pcb-build]');
await p.waitForSelector('[data-testid=pcb-result]', { timeout: 400000 });
const before = await p.evaluate(async () => (await (await fetch(document.querySelector('.pcb-picture img').src.replace(/path=[^&]*/, 'path=layout.json'))).json()).parts?.find((x) => x.ref === 'D1'));
await p.click('[data-testid=pcb-arrange]');
const part = p.locator('[data-testid=board-editor] g[data-ref=D1] rect');
await part.scrollIntoViewIfNeeded();
const box = await part.boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down();
await p.mouse.move(box.x + box.width / 2 + 160, box.y + box.height / 2 + 10, { steps: 8 });
await p.mouse.up();
await p.locator('[data-testid=board-editor]').screenshot({ path: 'test-results/board-editor.png' });
const disabled = await p.isDisabled('[data-testid=be-apply]');
console.log('apply enabled:', !disabled, await p.textContent('[data-testid=be-apply]'));
await p.click('[data-testid=be-apply]');
await p.waitForSelector('[data-testid=pcb-progress]');
await p.waitForSelector('[data-testid=pcb-result]', { timeout: 400000 });
const verdict = await p.textContent('.pcb-verdict');
const after = await p.evaluate(async () => (await (await fetch(document.querySelector('.pcb-picture img').src.replace(/path=[^&]*/, 'path=layout.json'))).json()).parts?.find((x) => x.ref === 'D1'));
console.log('D1 before', before, '\nD1 after', after);
console.log('verdict:', verdict.replace(/\s+/g, ' ').slice(0, 160));
await p.screenshot({ path: 'test-results/board-editor-after.png' });
console.log('errors:', errors);
await b.close();
const pass = /Ready to order/.test(verdict) && Math.abs(after.x - before.x) > 5 && !errors.length;
console.log(pass ? 'PASS' : 'FAIL');
process.exit(pass ? 0 : 1);
