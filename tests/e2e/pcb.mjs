// E2E: the Circuit board tab designs, checks and exports a real PCB (needs KiCad + Freerouting on this machine).
import { chromium } from 'playwright';
const ex = process.argv[2] ?? 'esp32-weather-imu';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })).newPage();
const errors = [];
p.on('pageerror', (e) => errors.push(String(e)));
await p.goto(`http://localhost:5173/?example=${ex}&notour`);
await p.evaluate(() => localStorage.clear());
await p.goto(`http://localhost:5173/?example=${ex}&notour`);
await p.waitForSelector('.part');
await p.click('.tabs button:has-text("Circuit board")');
await p.waitForSelector('[data-testid=pcb-build]');
await p.screenshot({ path: `test-results/pcb-${ex}-start.png` });
await p.selectOption('[data-testid=pcb-fab]', 'pcbway');
await p.fill('[data-testid=pcb-qr]', 'https://example.com/build');
await p.click('[data-testid=pcb-build]');
await p.waitForSelector('[data-testid=pcb-progress]');
await p.waitForTimeout(3000);
await p.screenshot({ path: `test-results/pcb-${ex}-progress.png` });
await p.waitForSelector('[data-testid=pcb-result]', { timeout: 300000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: `test-results/pcb-${ex}-result.png` });
const verdict = await p.textContent('.pcb-verdict');
const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-testid=pcb-gerbers]')]);
const path = `test-results/${dl.suggestedFilename()}`;
await dl.saveAs(path);
await p.click('.pcb-toggle button:has-text("Copper tracks")');
await p.waitForTimeout(1500);
await p.screenshot({ path: `test-results/pcb-${ex}-copper.png` });
console.log('verdict:', verdict.replace(/\s+/g, ' ').slice(0, 300));
console.log('download:', path);
console.log('errors:', errors);
await b.close();
process.exit(/Ready to order/.test(verdict) && /PCBWay/.test(verdict) && !errors.length ? 0 : 1);
