import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
await p.goto('http://localhost:5173/?example=esp32-internet-clock&notour');
await p.waitForTimeout(3000);
await p.locator('.tabs button', { hasText: 'Build guide' }).click();
await p.waitForTimeout(1500);
const txt = await p.locator('body').innerText();
const i = txt.indexOf('Load the program');
console.log('GUIDE:', txt.slice(i, i + 1500));
console.log('has LATITUDE:', txt.includes('LATITUDE'), 'has UTC_OFFSET:', txt.includes('UTC_OFFSET'));
const el = p.getByText('LATITUDE').first();
if (await el.count()) await el.scrollIntoViewIfNeeded();
await p.screenshot({ path: 'test-results/qa2/repro-clock/guide.png' });
await p.locator('.tabs button', { hasText: 'Code' }).click();
await p.waitForTimeout(1500);
const code = await p.locator('body').innerText();
console.log('code LATITUDE:', code.includes('LATITUDE'), 'code UTC_OFFSET:', code.match(/UTC_OFFSET_H.*/)?.[0]);
await p.screenshot({ path: 'test-results/qa2/repro-clock/code.png' });
await b.close();
