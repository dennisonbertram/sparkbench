import { chromium } from 'playwright';
import fs from 'node:fs';
const D='test-results/qa/nia-newbie/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1366, height: 820 } });
await ctx.addInitScript(()=>{try{localStorage.setItem('sparkbench.tour.done','1')}catch{}});
const p = await ctx.newPage();
const errs=[]; p.on('console',m=>{if(m.type()==='error'||m.type()==='warning')errs.push(m.type()+': '+m.text())}); p.on('pageerror',e=>errs.push('pageerror: '+e.message+'\n'+e.stack));
p.on('response', async r=>{ if(r.url().includes('/api/ai')) { const t=await r.text(); fs.writeFileSync(D+'ai-'+Date.now()+'.json', t); console.log('AI RESP', r.status(), t.slice(0,600)); }});
await p.goto('http://localhost:5173/?welcome'); await p.waitForTimeout(1500);
await p.fill('.hero-input textarea','a thermometer with a screen for my desk');
await p.click('button.primary.big'); await p.waitForSelector('.part',{timeout:240000});
await p.waitForFunction(()=>!document.querySelector('.msg.pending'),null,{timeout:180000});
await p.fill('.composer textarea', "make it beep when it's too hot"); await p.press('.composer textarea','Enter');
await p.waitForTimeout(1000); await p.screenshot({ path: D+'80-beep-pending.png' });
await p.waitForFunction(()=>!document.querySelector('.msg.pending'),null,{timeout:240000}).catch(e=>console.log('wait err',e.message));
await p.waitForTimeout(1000);
await p.screenshot({ path: D+'81-beep-done.png' });
console.log('has welcome?', !!(await p.$('.welcome')), 'parts', await p.$$eval('.part', es=>es.map(e=>e.getAttribute('data-part'))));
console.log('ERRS', errs.join('\n'));
await b.close();
