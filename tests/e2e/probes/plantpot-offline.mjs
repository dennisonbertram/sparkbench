import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage({viewport:{width:1440,height:900}});
await p.route('**/api/status', r => r.fulfill({json:{ai:{enabled:false}}}));
await p.route('**/api/ai/**', r => r.fulfill({status:503, json:{error:'off'}}));
await p.goto('http://localhost:5173/?welcome&notour');
await p.click('.hero-input textarea');
await p.keyboard.type('ESP32 plant pot moisture monitor with a soil moisture sensor and an OLED display showing the moisture percentage');
await p.click('button.primary.big');
await p.waitForSelector('.part', {timeout:60000});
await p.waitForTimeout(2000);
console.log('badge:', await p.textContent('.ai-badge'));
console.log('parts:', await p.$$eval('.part', els=>els.map(e=>e.getAttribute('data-part'))));
await p.click('button.run'); await p.waitForTimeout(5000);
await p.screenshot({path:'test-results/qa/plantpot/10-offline-board.png'});
console.log('serial:', (await p.textContent('[data-testid=serial]')).slice(0,300));
console.log('knob text:', await p.evaluate(()=>document.body.innerText.match(/[^\n]*(knob|potentiometer)[^\n]*/gi)));
await p.click('button.run');
await p.click('.tabs button:has-text("Parts list")'); await p.waitForTimeout(800);
await p.screenshot({path:'test-results/qa/plantpot/11-offline-parts.png'});
await p.click('.tabs button:has-text("Build guide")'); await p.waitForTimeout(800);
console.log('guide knob:', await p.evaluate(()=>document.body.innerText.match(/[^\n]*knob[^\n]*/gi)));
await b.close();
