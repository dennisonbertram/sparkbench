import { chromium } from 'playwright';
const D='test-results/qa2/repro-555beep/';
const b = await chromium.launch(); const p = await b.newPage({viewport:{width:1366,height:820}});
await p.goto('http://localhost:5173/?welcome&notour'); await p.waitForTimeout(2000);
await p.fill('.hero-input textarea','a 555 circuit that beeps'); await p.click('.hero-input button');
await p.waitForSelector('.composer textarea',{timeout:240000});
await p.waitForFunction(()=>document.querySelectorAll('.msg.ai:not(.pending)').length>0 && !document.querySelector('.msg.ai.pending'),null,{timeout:240000});
await p.waitForTimeout(2000);
console.log('REPLY1:', await p.locator('.msg.ai:not(.pending)').last().innerText());
console.log('PARTS1:', await p.$$eval('.part', els=>els.map(e=>e.dataset.part).join(',')));
console.log('TITLE1:', await p.title(), '|', await p.locator('header, .topbar').first().innerText().catch(()=>''));
await p.screenshot({path:D+'01-design.png'});
const n0 = await p.locator('.msg.ai:not(.pending)').count();
await p.fill('.composer textarea','I really want it to beep - use a piezo buzzer instead of the LED so I can hear it'); await p.press('.composer textarea','Enter');
await p.waitForTimeout(1000);
await p.waitForFunction(n=>document.querySelectorAll('.msg.ai:not(.pending)').length>n && !document.querySelector('.msg.ai.pending'), n0, {timeout:240000});
await p.waitForTimeout(2000);
console.log('REPLY2:', await p.locator('.msg.ai:not(.pending)').last().innerText());
console.log('PARTS2:', await p.$$eval('.part', els=>els.map(e=>e.dataset.part).join(',')));
console.log('TITLE2:', await p.title(), '|', await p.locator('header, .topbar').first().innerText().catch(()=>''));
await p.screenshot({path:D+'02-followup.png'});
await p.locator('.tabs button',{hasText:'Blog post'}).click(); await p.waitForTimeout(1500);
await p.screenshot({path:D+'03-blog.png'});
await b.close();
