import { chromium } from 'playwright';
import fs from 'fs';
const D='test-results/qa2/repro-badgename';
const browser = await chromium.launch();
const page = await (await browser.newContext({viewport:{width:1440,height:900}})).newPage();
await page.goto('http://localhost:5173/?welcome&notour');
await page.fill('.hero-input textarea','an ESP32 e-ink badge that shows my name and the weather');
await page.click('.hero-input button');
await page.waitForSelector('[data-testid="breadboard"] .part',{timeout:240000});
await page.waitForTimeout(2000);
await page.screenshot({path:`${D}/01-designed.png`});
const getCode = async()=>{ await page.click('.tabs button:has-text("Code")'); await page.waitForTimeout(800);
  const t = await page.evaluate(()=>{const m=window.monaco?.editor?.getModels?.(); if(m&&m.length) return m.map(x=>x.getValue()).join('\n----\n'); const cm=document.querySelector('.cm-content'); return cm?cm.innerText:document.querySelector('textarea')?.value||document.body.innerText;});
  await page.click('.tabs button:has-text("Breadboard")'); await page.waitForTimeout(500); return t; };
fs.writeFileSync(`${D}/main-before.py`, await getCode());
await page.click('button.run'); await page.waitForTimeout(8000);
await page.screenshot({path:`${D}/02-run.png`});
await page.click('button.run'); await page.waitForTimeout(800);
const n0 = await page.locator('.msg.ai:not(.pending)').count();
await page.fill('.composer textarea','Add a button that refreshes the weather right away when I press it');
await page.press('.composer textarea','Enter');
await page.waitForFunction(n=>document.querySelectorAll('.msg.ai:not(.pending)').length>n && !document.querySelector('.msg.ai.pending'), n0, {timeout:300000});
await page.waitForTimeout(3000);
const msgs = await page.locator('.msg.ai:not(.pending)').allInnerTexts();
console.log('REPLY:', msgs[msgs.length-1]);
await page.screenshot({path:`${D}/03-after-followup.png`});
fs.writeFileSync(`${D}/main-after.py`, await getCode());
const acc = page.locator('button:has-text("Accept")'); if (await acc.count()) { console.log('accept button present'); }
await page.click('button.run'); await page.waitForTimeout(8000);
await page.screenshot({path:`${D}/04-run-after.png`});
const ser = await page.locator('[data-testid=serial]').innerText().catch(()=>'');
console.log('SERIAL:', ser.slice(-800));
await browser.close();
