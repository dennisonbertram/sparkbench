import { chromium } from 'playwright';
const D='test-results/qa2/repro555np/';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1500, height: 950 } });
await page.goto('http://localhost:5173/?example=555-tone&notour');
await page.waitForTimeout(2500);
await page.screenshot({ path: D+'open.png' });
const prob = page.locator('.console-tabs button', { hasText: 'Problems' });
console.log('problems tab:', await prob.innerText());
await prob.click(); await page.waitForTimeout(500);
console.log('PROBLEMS idle:', await page.locator('[data-testid=problems]').innerText());
console.log('U1 text:', await page.locator('.part[data-part=U1]').innerText().catch(e=>'ERR'));
await page.locator('button.run').click(); await page.waitForTimeout(2000);
await page.screenshot({ path: D+'run.png' });
console.log('problems tab running:', await prob.innerText());
const mom = page.locator('.momentary').first();
console.log('momentary count', await page.locator('.momentary').count(), await mom.innerText().catch(()=>''));
const box = await mom.boundingBox();
await page.mouse.move(box.x+box.width/2, box.y+box.height/2); await page.mouse.down();
await page.waitForTimeout(2500);
await page.screenshot({ path: D+'held.png' });
console.log('problems tab held:', await prob.innerText());
console.log('PROBLEMS held:', await page.locator('[data-testid=problems]').innerText());
await page.locator('.console-tabs button').first().click(); await page.waitForTimeout(800);
await page.screenshot({ path: D+'held-scope.png' });
console.log('BODY snippet:', ((await page.locator('body').innerText()).match(/[^\n]*(Hz|No power|VCC)[^\n]*/g)||[]).slice(0,12).join('\n'));
await page.mouse.up();
await b.close();
