import { chromium } from 'playwright';
import fs from 'fs';
const D='test-results/qa2/repro-pins/';
const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:1440,height:900}}); const p=await ctx.newPage();
const log=(...a)=>{console.log(...a); fs.appendFileSync(D+'log2.txt',a.join(' ')+'\n');};
const done=(n)=>p.waitForFunction((n)=>document.querySelectorAll('.msg.ai:not(.pending)').length>n && !document.querySelector('.msg.pending'),n,{timeout:300000});
const details=()=>p.evaluate(()=>{document.querySelectorAll('details.msg-details').forEach(d=>d.open=true); return [...document.querySelectorAll('details.msg-details')].map((d,i)=>'#'+i+'\n'+d.innerText).join('\n');});
const code=async()=>{await p.locator('.tabs button',{hasText:'Code'}).first().click(); await p.waitForTimeout(1000); const t=await p.evaluate(()=>{const e=document.querySelector('.cm-content, .monaco-editor, textarea, pre'); return e?e.innerText:''}); await p.locator('.tabs button',{hasText:'Breadboard'}).first().click(); return t.split('\n').filter(l=>/Pin\(|GP\d|PIN|= *\d+/.test(l)).slice(0,40).join('\n');};
await p.goto('http://localhost:5173/?welcome&notour'); await p.waitForTimeout(1500);
await p.fill('.hero-input textarea','a Pico reaction-time game with three buttons, three LEDs and a buzzer');
await p.click('.hero-input button');
await p.waitForSelector('.composer textarea',{timeout:300000}); await done(0); await p.waitForTimeout(2000);
log('DETAILS1>>>\n'+await details()); log('CODE1>>>\n'+await code());
await details(); await p.screenshot({path:D+'11-before.png'});
const n=await p.locator('.msg.ai:not(.pending)').count();
await p.fill('.composer textarea','Add an OLED screen that shows the last reaction time and the best score');
await p.press('.composer textarea','Enter'); await p.waitForTimeout(3000); await done(n); await p.waitForTimeout(2000);
log('REPLY2>>>\n'+await p.evaluate(()=>[...document.querySelectorAll('.msg.ai')].pop().innerText));
log('DETAILS2>>>\n'+await details()); log('CODE2>>>\n'+await code());
await details(); await p.evaluate(()=>{const l=document.querySelector('.chat-log'); l.scrollTop=l.scrollHeight;});
await p.screenshot({path:D+'12-after.png'});
await b.close();
