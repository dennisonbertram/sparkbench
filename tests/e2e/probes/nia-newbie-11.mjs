import { chromium } from 'playwright';
const D='test-results/qa/nia-newbie/';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1366, height: 820 } });
await ctx.addInitScript(()=>{try{localStorage.setItem('sparkbench.tour.done','1')}catch{}});
const p = await ctx.newPage();
await p.goto('http://localhost:5173/?example=esp32-parking-sensor&notour'); await p.waitForSelector('.part'); await p.waitForTimeout(800);
await p.click('button:has-text("Export")'); await p.waitForTimeout(400);
await p.screenshot({ path: D+'B0-export.png' });
console.log('EXPORT MENU:', await p.innerText('.menu, [role=menu], .dropdown').catch(()=>'?'));
await p.click('button:has-text("Export")'); await p.waitForTimeout(300);
await p.click('button.run'); await p.waitForTimeout(1500);
const sl = await p.$$eval('.simctl input', es=>es.map(e=>e.getAttribute('aria-label')));
console.log('sliders', sl); await p.screenshot({path:D+'B0b-running.png'}); console.log('run state', await p.innerText('.run-group'));
await p.locator('input[aria-label=Distance]').fill('8'); await p.waitForTimeout(2500);
await p.screenshot({ path: D+'B1-parking-close.png' });
console.log('buzzer html:', await p.$eval('.part[data-part^=buzzer]', e=>e.outerHTML.slice(0,800)).catch(()=>'none'));
console.log('sound btn:', await p.$eval('button:has-text("Sound")', e=>e.outerHTML));
await p.click('button:has-text("Tour")'); await p.waitForTimeout(500);
console.log('tour reopened:', !!(await p.$('.tour-card')));
await b.close();
