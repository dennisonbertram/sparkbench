import { open, OUT } from './r2-regression-lib.mjs';
const {b,p} = await open('?example=pico-night-light&notour');
await p.waitForTimeout(1500);
await p.goto('http://localhost:5173/?notour'); await p.waitForTimeout(2000);
const st = ()=>p.evaluate(()=>({cur:localStorage.getItem('sparkbench.current.v1'), names:Object.values(JSON.parse(localStorage.getItem('sparkbench.projects.v1')||'{}')).map(x=>x.id+':'+x.name)}));
console.log('before', await st(), 'title', await p.locator('header').first().innerText().catch(()=>''));
p.on('dialog', d=>{console.log('dialog', d.message()); d.accept();});
await p.click('button.brand'); await p.waitForTimeout(500);
const rows = await p.locator('.projects-menu .menu-row').allInnerTexts(); console.log('menu rows', rows);
const cur = (await st()).cur;
const name = (await st()).names.find(n=>n.startsWith(cur+':')).split(':')[1];
await p.locator(`.projects-menu button[aria-label="Delete ${name}"]`).first().click();
await p.waitForTimeout(1500);
console.log('after delete', await st(), 'welcome?', await p.locator('.hero-input').count());
await p.screenshot({path:OUT+'delete-1.png'});
await p.reload(); await p.waitForTimeout(2500);
console.log('after reload', await st(), 'welcome?', await p.locator('.hero-input').count(), 'parts', await p.locator('.part').count());
await p.screenshot({path:OUT+'delete-2-reload.png'});
await b.close();
