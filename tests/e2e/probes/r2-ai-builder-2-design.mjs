import * as L from './r2-ai-builder-2-lib.mjs';
const [prof, prompt] = process.argv.slice(2);
const { ctx, p, errs } = await L.open('http://localhost:5173/?welcome&notour', prof);
await L.shot(p, prof + '-00-welcome');
setTimeout(() => L.shot(p, prof + '-01-designing').catch(()=>{}), 8000);
const secs = await L.design(p, prompt);
console.log('design secs', secs);
await L.shot(p, prof + '-02-designed');
console.log('STATE', JSON.stringify(await L.state(p)));
console.log('MSGS\n', await L.allMsgs(p));
console.log('PROBLEMS\n', await L.problems(p));
await L.run(p); await p.waitForTimeout(6000);
await L.shot(p, prof + '-03-running');
console.log('SERIAL\n', await L.serial(p));
console.log('SIMCTL\n', await L.simctl(p));
console.log('CODE\n', await L.code(p));
await L.shot(p, prof + '-04-code');
console.log('ERRS', errs.join('\n'));
await ctx.close();
