import { chromium } from 'playwright';
const out = 'test-results/qa/verify-react';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
await p.route('**/api/status', r => r.fulfill({ json: { ai: { enabled: false }, kicad: true, ngspice: true } }));
await p.route('**/api/ai/**', r => r.abort());
await p.goto('http://localhost:5173/?welcome&notour');
await p.click('.hero-input textarea');
await p.keyboard.type('ESP32 reaction time game with 3 buttons, 3 LEDs and a buzzer');
await p.click('button.primary.big');
await p.waitForSelector('button.run', { timeout: 60000 });
await p.waitForTimeout(4000);
await p.screenshot({ path: `${out}/01-designed.png` });
await p.locator('.tabs button', {hasText:'Code'}).click(); await p.waitForTimeout(800); await p.screenshot({ path: `${out}/01b-code.png` }); await p.locator('.tabs button', {hasText:'Breadboard'}).click(); await p.waitForTimeout(800);
await p.click('button.run'); await p.waitForTimeout(3000);
const btns = p.locator('button.momentary');
console.log('momentary:', await btns.allInnerTexts());
const press = async (i, name) => { const bt = btns.nth(i); const bb = await bt.boundingBox(); await p.mouse.move(bb.x+bb.width/2, bb.y+bb.height/2); await p.mouse.down(); await p.waitForTimeout(300); await p.mouse.up(); await p.waitForTimeout(900); await p.screenshot({ path: `${out}/${name}.png` }); };
await press(0,'02-pressA'); await press(2,'03-pressC'); await press(1,'04-pressB');
console.log('SERIAL:', (await p.locator('[data-testid=serial]').innerText()).slice(-400));
await b.close();
