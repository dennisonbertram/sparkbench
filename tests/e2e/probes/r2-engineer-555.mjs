import { chromium } from 'playwright';
const out = 'test-results/qa2/engineer';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1500, height: 1000 } });
await page.goto(`http://localhost:5173/?example=555-tone&notour`);
await page.waitForTimeout(2000);
await page.click('button.run');
await page.waitForTimeout(1500);
const btn = page.locator('.simctl button, .momentary', { hasText: 'Press' }).first();
console.log('momentary count', await page.locator('.momentary').count());
const bb = await btn.boundingBox();
await page.mouse.move(bb.x + bb.width/2, bb.y + bb.height/2);
await page.mouse.down();
await page.waitForTimeout(3000);
await page.locator('.console-tabs button', { hasText: 'Scope' }).first().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/555-tone-held-scope.png` });
console.log('SCOPE:', await page.locator('.console-tabs ~ *').allInnerTexts().catch(()=>'' ));
await page.locator('.console-tabs button', { hasText: 'Problems' }).first().click();
await page.waitForTimeout(500);
console.log('PROBLEMS:', await page.locator('[data-testid=problems]').innerText().catch(e=>'ERR '+e.message));
await page.screenshot({ path: `${out}/555-tone-held-problems.png` });
await page.mouse.up();
await b.close();
