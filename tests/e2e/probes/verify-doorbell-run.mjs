import { chromium } from 'playwright';
import fs from 'fs';
const dir = 'test-results/qa/verify-doorbell';
const ai = JSON.parse(fs.readFileSync('test-results/qa/builder-pico-pi/doorbell/ai.json', 'utf8'));
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await p.goto('http://localhost:5173/?notour');
await p.evaluate((proj) => { localStorage.setItem('sparkbench.projects.v1', JSON.stringify({ [proj.id]: proj })); localStorage.setItem('sparkbench.current.v1', proj.id); }, ai.project);
await p.goto('http://localhost:5173/?notour');
await p.waitForSelector('.part', { timeout: 30000 });
await p.waitForTimeout(2000);
await p.click('button.run');
await p.waitForTimeout(3000);
await p.screenshot({ path: `${dir}/01-running.png` });
const before = await p.locator('[data-testid=serial]').innerText().catch(()=>'');
const btns = p.locator('.momentary');
console.log('momentary:', await btns.allInnerTexts());
await btns.first().hover(); await p.mouse.down(); await p.waitForTimeout(400); await p.mouse.up();
await p.waitForTimeout(2000);
await p.screenshot({ path: `${dir}/02-after-press.png` });
console.log('BEFORE:', before.slice(-400));
console.log('AFTER:', (await p.locator('[data-testid=serial]').innerText().catch(()=>'')).slice(-800));
console.log('STATUS:', await p.locator('header').first().innerText().catch(()=>''));
await b.close();
