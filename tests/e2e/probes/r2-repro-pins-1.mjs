import { chromium } from 'playwright';
import fs from 'fs';
const D='test-results/qa2/repro-pins/';
const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:1440,height:900}}); const p=await ctx.newPage();
const log=(...a)=>{console.log(...a); fs.appendFileSync(D+'log.txt',a.join(' ')+'\n');};
await p.goto('http://localhost:5173/?welcome&notour'); await p.waitForTimeout(1500);
await p.fill('.hero-input textarea','a Pico reaction-time game with three buttons, three LEDs and a buzzer');
await p.click('.hero-input button');
await p.waitForSelector('.composer textarea',{timeout:300000});
await p.waitForFunction(()=>document.querySelectorAll('.msg.ai:not(.pending)').length>0 && !document.querySelector('.msg.pending'),null,{timeout:300000});
await p.waitForTimeout(2000);
const pins=async()=>{await p.locator('.console-tabs button',{hasText:'Pins'}).first().click(); await p.waitForTimeout(500); return p.evaluate(()=>{const t=[...document.querySelectorAll('.console-tabs ~ *, [data-testid=pins]')].map(e=>e.innerText).join('\n'); return t;});};
const chat=()=>p.evaluate(()=>[...document.querySelectorAll('.msg')].map(m=>(m.className.includes('ai')?'AI: ':'ME: ')+m.innerText).join('\n---\n'));
const wires=()=>p.evaluate(()=>[...document.querySelectorAll('[data-wire], .wire')].length);
log('CHAT1>>>\n'+await chat());
log('PINS1>>>\n'+await pins());
await p.screenshot({path:D+'01-before.png'});
const n=await p.locator('.msg.ai:not(.pending)').count();
await p.fill('.composer textarea','Add an OLED screen that shows the last reaction time and the best score');
await p.press('.composer textarea','Enter');
await p.waitForTimeout(3000);
await p.waitForFunction((n)=>document.querySelectorAll('.msg.ai:not(.pending)').length>n && !document.querySelector('.msg.pending'),n,{timeout:300000});
await p.waitForTimeout(2000);
log('CHAT2>>>\n'+await chat());
log('PINS2>>>\n'+await pins());
await p.screenshot({path:D+'02-after.png'});
await b.close();
