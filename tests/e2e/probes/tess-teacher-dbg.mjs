import { chromium } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1400, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
page.on('console', m => console.log('console', m.type(), m.text()));
page.on('download', d => console.log('DOWNLOAD', d.suggestedFilename()));
await page.goto(`http://localhost:5173/?example=esp32-weather-imu&notour`);
await page.waitForSelector('.part');
await page.waitForTimeout(1000);
await page.click('header button.primary:has-text("Export")');
await page.waitForTimeout(300);
await page.click('.menu button:has-text("Project file")');
await page.waitForTimeout(2000);
console.log('menu visible?', await page.locator('.menu').count());
await page.click('header button.primary:has-text("Export")');
await page.waitForTimeout(300);
await page.click('.menu button:has-text("Everything")');
await page.waitForTimeout(3000);
await browser.close();
