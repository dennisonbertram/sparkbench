// Library status report: what is in the library, what is waiting for review (and why), what failed,
// and what the simulator can't model yet. Run: npx tsx scripts/parts/report.ts  (writes docs/PARTS-LIBRARY.md)
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PARTS } from '../../src/core/parts';

const read = (f: string) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null);
const catalog = read('scripts/parts/catalog.json') as { supported: { mpn: string; form: string; family: string }[]; later: { mpn: string; why: string }[] };
const slugOf = (mpn: string) => mpn.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const lib = readdirSync('.claude/skills')
  .filter((d) => d.startsWith('part-') && existsSync(join('.claude/skills', d, 'part.json')))
  .map((d) => ({ dir: d, spec: read(join('.claude/skills', d, 'part.json')), check: read(join('.claude/skills', d, 'check.json')) }));
const staged = existsSync('parts-staging') ? readdirSync('parts-staging').filter((d) => d.startsWith('part-')) : [];

const published = new Set(lib.map((l) => l.dir.replace(/^part-/, '')));
const rows: string[] = [];
const review: string[] = [];
const failed: string[] = [];
let pending = 0;
for (const c of catalog.supported) {
  const slug = slugOf(c.mpn);
  if (published.has(slug)) continue;
  const dir = join('parts-staging', `part-${slug}`);
  if (!staged.includes(`part-${slug}`)) {
    pending++;
    continue;
  }
  const rv = read(join(dir, 'review.json'));
  const ck = read(join(dir, 'check.json'));
  const outcome = read(join(dir, 'outcome.json'));
  if (rv) review.push(`| ${c.mpn} | ${rv.diffs.join('; ').replace(/\|/g, '/')} |`);
  else if (outcome && outcome.status !== 'pass') failed.push(`| ${c.mpn} | ${outcome.status} | ${String(outcome.reason).replace(/\|/g, '/')} |`);
  else if (ck && !ck.pass) {
    const bad = [...Object.entries(ck.boards).flatMap(([b, st]: any) => st.filter((s: any) => s.status === 'fail').map((s: any) => `[${b}] ${s.stage}: ${s.detail}`)), ...ck.part.filter((s: any) => s.status === 'fail').map((s: any) => `${s.stage}: ${s.detail}`)];
    failed.push(`| ${c.mpn} | check failed | ${bad.join('; ').slice(0, 300).replace(/\|/g, '/')} |`);
  } else pending++;
}
for (const l of lib) {
  const s = l.spec;
  const st = s.library?.status === 'checked' ? 'checked in simulation + independent datasheet reading' : l.check?.pass ? 'passes the part check' : 'datasheet only (older)';
  rows.push(`| ${s.mpn} | ${s.name} | ${s.interface} | ${st} |`);
}

const md = `# Parts library

Generated by \`npx tsx scripts/parts/report.ts\`. How a part gets in: [the part check](../scripts/parts/check.ts) (wiring, design checks, breadboard plan, simulator example + test on ESP32 and Pico, KiCad footprint, a routed DRC-clean circuit board, LCSC stock) and then [publish](../scripts/parts/publish.ts), which compares the part with a blind second reading of the datasheet (header pin order, roles, I2C address, supply range, conversion constants, chip ID). Any disagreement goes to review instead of the library.

**Nothing here has been tested on real hardware yet.** "Checked" means the simulator, the circuit-board tools and two independent datasheet readings agree.

- Built-in parts (hand-modelled): ${PARTS.filter((p) => !p.production).length}
- Library parts: ${lib.length}
- Waiting for review: ${review.length}
- Didn't make it: ${failed.length}
- Not attempted yet: ${pending}
- Needs a new kind of simulator model first: ${catalog.later.length}

## In the library

| Part | Name | Interface | Status |
|---|---|---|---|
${rows.join('\n')}

## Waiting for review (the two datasheet readings disagree)

| Part | Differences |
|---|---|
${review.join('\n') || '| – | – |'}

## Didn't make it

| Part | Outcome | Why |
|---|---|---|
${failed.join('\n') || '| – | – | – |'}

## Needs a new kind of simulator model

| Part | Why |
|---|---|
${catalog.later.map((l) => `| ${l.mpn} | ${l.why} |`).join('\n')}
`;
writeFileSync('docs/PARTS-LIBRARY.md', md);
console.log(`library ${lib.length}, review ${review.length}, failed ${failed.length}, pending ${pending}`);
