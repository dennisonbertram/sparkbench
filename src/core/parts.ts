// The parts library. Every part the planner, schematic, simulator and BOM know about.
import type { PartDef, PinDef } from './types';
import { BOARDS } from './boards';

const p = (name: string, role: PinDef['role'], fn?: string, extra: Partial<PinDef> = {}): PinDef => ({ name, role, fn, ...extra });

const boardPins = (id: 'esp32' | 'pico' | 'rpi4'): PinDef[] =>
  BOARDS[id].pins.map((bp) =>
    p(bp.name, bp.role === 'gnd' ? 'gnd' : bp.role === 'power' ? 'power' : 'io', bp.gpio !== undefined ? `gpio${bp.gpio}` : undefined, {
      required: false,
      description: [bp.gpio !== undefined ? `GPIO${bp.gpio}` : '', ...(bp.alt ?? []), bp.caution ?? ''].filter(Boolean).join(' · '),
    }),
  );

const fmtOhms = (o: number) => (o >= 1e6 ? `${+(o / 1e6).toFixed(2)}M` : o >= 1000 ? `${+(o / 1000).toFixed(2)}k` : `${o}`);
export const formatOhms = fmtOhms;
const fmtFarads = (f: number) => (f >= 1e-6 ? `${+(f * 1e6).toFixed(2)}µF` : f >= 1e-9 ? `${+(f * 1e9).toFixed(2)}nF` : `${+(f * 1e12).toFixed(0)}pF`);
export const formatFarads = fmtFarads;

