// Self-test firmware: a selftest.py for the real board that checks every part, in order, and prints
// one machine-readable line per check:
//   PASS <part>: <what>      automatic check passed (e.g. I2C device answered, reading plausible)
//   FAIL <part>: <what+fix>  automatic check failed, with the likely wiring fix
//   ACTION <part>: <do this> it needs you (press a button, turn the knob) — then PASS/FAIL follows
//   LOOK <part>: <see this>  an output to confirm by eye/ear (LED blinks, buzzer beeps, servo moves)
//   SELFTEST DONE: <passed> passed, <failed> failed, <look> to check by eye
// The same file runs in the simulator, so the real board's output can be compared line by line.
import type { FeatureInstance, Project } from './types';
import { generateFiles } from './codegen';
import { partDef } from './parts';
import { BOARDS } from './boards';

const I2C_KINDS = new Set(['oled', 'lcd', 'mpu6050']);

/** The import lines and the "hardware setup" section of the generated program. */
function setupOf(project: Project): { imports: string[]; setup: string[] } {
  const main = generateFiles({ ...project, codeCustom: false })['main.py'] ?? '';
  const head = main.slice(0, main.indexOf('# ----'));
  const imports = head.split('\n').filter((l) => /^(import|from) /.test(l));
  const a = main.indexOf('# ---- hardware setup ----');
  const b = main.indexOf('# ----', a + 10);
  const setup = a >= 0 ? main.slice(a, b > a ? b : undefined).split('\n').filter((l) => l.trim() && !l.startsWith('# ----')) : [];
  return { imports, setup };
}

export function generateSelfTest(project: Project): string | null {
  // An Arduino sketch board (Nicla Voice) has no Python self-test.
  if (project.board === 'none' || BOARDS[project.board].language === 'arduino' || !project.features?.length) return null;
  const pi = project.board === 'rpi4';
  const { imports, setup } = setupOf(project);
  const fs = project.features;
  const L: string[] = [];
  const add = (...xs: string[]) => L.push(...xs);
  add(
    `# Self-test for "${project.name}" — generated by Sparkbench.`,
    '# Copy it to the board next to main.py and run it once (see the build guide).',
    '# It checks every part in turn and tells you what to fix.',
    '',
    ...imports,
    ...(imports.some((l) => /^import time\b/.test(l)) ? [] : ['import time']),
    ...(imports.some((l) => /^import math\b/.test(l)) ? [] : ['import math']),
    '',
    'passed = 0',
    'failed = 0',
    'look = 0',
    '',
    'def report(name, ok, msg):',
    '    global passed, failed',
    '    if ok:',
    '        passed += 1',
    '    else:',
    '        failed += 1',
    "    print(('PASS ' if ok else 'FAIL ') + name + ': ' + msg)",
    '',
    'def see(name, msg):',
    '    global look',
    '    look += 1',
    "    print('LOOK ' + name + ': ' + msg)",
    '',
    ...(pi
      ? [
          'def ms():',
          '    return int(time.monotonic() * 1000)',
          '',
          'def sleep_ms(n):',
          '    time.sleep(n / 1000)',
        ]
      : ['def ms():', '    return time.ticks_ms()', '', 'def sleep_ms(n):', '    time.sleep_ms(n)']),
    '',
    'def wait_for(name, action, test, secs=15, fix=""):',
    "    print('ACTION ' + name + ': ' + action + ' (you have ' + str(secs) + ' s)')",
    '    t0 = ms()',
    '    while ms() - t0 < secs * 1000:',
    '        if test():',
    "            report(name, True, 'seen')",
    '            return True',
    '        sleep_ms(10)',
    "    report(name, False, 'nothing happened. ' + fix)",
    '    return False',
    '',
    "print('SELFTEST START: " + project.name.replace(/'/g, '') + "')",
    '',
    ...guardedSetup(setup, fs),
    '',
  );

  // I2C bus: every display/sensor must answer at its address.
  const i2cParts = fs.filter((f) => I2C_KINDS.has(f.kind));
  if (i2cParts.length) {
    const want = i2cParts.map((f) => [f, project.parts.find((p) => p.id === f.parts[0])] as const).filter(([, p]) => p && partDef(p.type).i2cAddress !== undefined);
    if (pi) {
      add('from smbus2 import SMBus', 'found = []', 'with SMBus(1) as bus:', '    for a in range(0x08, 0x78):', '        try:', '            bus.read_byte(a)', '            found.append(a)', '        except OSError:', '            pass');
    } else add('found = i2c.scan()');
    add("print('INFO I2C: %d part(s) answered on the shared SDA/SCL data wires' % len(found))");
    for (const [f, p] of want) {
      const addr = partDef(p!.type).i2cAddress!;
      add(`report(${JSON.stringify(f.label)}, ${addr} in found, 'is connected and answering' if ${addr} in found else ${JSON.stringify(`didn't answer: check its SDA wire goes to ${pinWords(f.pins.sda)} and SCL to ${pinWords(f.pins.scl)} (not swapped), and its power and GND wires`)})`);
    }
    add('');
  }

  for (const f of fs) {
    const body = featureTest(f, pi);
    if (!body.length) continue;
    // Skip parts whose setup failed (already reported, or explained by the I2C check).
    const guard = f.kind === 'hcsr04' && !pi ? `${f.name}_echo` : f.name;
    add(`if ${guard} is not None:`, ...body.map((l) => `    ${l}`), '');
  }

  add("print('SELFTEST DONE: %d passed, %d failed, %d to check by eye' % (passed, failed, look))");
  return L.join('\n') + '\n';
}

/** Each setup line in its own try/except, so one dead part doesn't stop the whole test. */
function guardedSetup(setup: string[], fs: FeatureInstance[]): string[] {
  const out: string[] = [];
  for (const line of setup) {
    const m = /^(\w+)\s*=\s*(.+)$/.exec(line);
    out.push('try:', `    ${line}`, 'except Exception as e:');
    if (m) {
      const f = fs.find((x) => x.name === m[1] || `${x.name}_echo` === m[1] || `${x.name}_trig` === m[1]);
      out.push(`    ${m[1]} = None`);
      if (f && !I2C_KINDS.has(f.kind)) out.push(`    report(${JSON.stringify(f.label)}, False, 'could not start (' + str(e) + '): check its wiring')`);
      else if (!f) out.push(`    print('INFO setup: ${m[1]} could not start (' + str(e) + ')')`);
    } else out.push('    pass');
  }
  return out;
}

function featureTest(f: FeatureInstance, pi: boolean): string[] {
  const n = f.name;
  const label = JSON.stringify(f.label);
  const pin = Object.values(f.pins).map(pinWords).join('/');
  const out = (on: string, off: string) => [`${on}`, 'sleep_ms(300)', `${off}`, 'sleep_ms(300)'];
  switch (f.kind) {
    case 'oled':
      return [`${n}.fill(0)`, `${n}.text('SELF TEST', 0, 0)`, `${n}.text('Screen OK', 0, 16)`, `${n}.show()`, `see(${label}, 'shows SELF TEST and Screen OK')`];
    case 'lcd':
      return [`${n}.clear()`, `${n}.putstr('SELF TEST')`, `see(${label}, 'shows SELF TEST (turn the contrast screw on the back if the screen is blank)')`];
    case 'epaper':
      return [`${n}.fill(1)`, `${n}.text('SELF TEST', 10, 10, 0)`, `${n}.show()`, `see(${label}, 'flashes, then shows SELF TEST')`];
    case 'mpu6050':
      return [`ax, ay, az = ${n}.accel()`, 'g = math.sqrt(ax * ax + ay * ay + az * az)', `report(${label}, 0.7 < g < 1.3, 'measures %.2f g lying still (expect about 1 g)' % g)`];
    case 'dht22':
      return pi
        ? [
            'try:',
            `    t, h = ${n}.temperature, ${n}.humidity`,
            `    report(${label}, t is not None and -20 < t < 60 and 0 <= h <= 100, 'reads %s C, %s %%' % (t, h))`,
            'except Exception as e:',
            `    report(${label}, False, 'no reading (' + str(e) + '): check DATA on ${pin} and its 10k pull-up')`,
          ]
        : [
            'try:',
            `    ${n}.measure()`,
            `    t, h = ${n}.temperature(), ${n}.humidity()`,
            `    report(${label}, -20 < t < 60 and 0 <= h <= 100, 'reads %.1f C, %.0f %%' % (t, h))`,
            'except OSError:',
            `    report(${label}, False, 'no reading: check DATA on ${pin} and that VCC is 3.3 V')`,
          ];
    case 'hcsr04':
      if (pi) return [`d = ${n}.distance * 100`, `report(${label}, 2 < d < 400, 'measures %.0f cm' % d)`];
      return [`${n}_trig.value(1)`, 'time.sleep_us(10)', `${n}_trig.value(0)`, `us = time_pulse_us(${n}_echo, 1, 30000)`, `report(${label}, us > 0 and 2 < us / 58 < 400, 'measures %.0f cm' % (us / 58) if us > 0 else 'no echo: check TRIG/ECHO wires and 5 V power')`];
    case 'pir':
      return pi ? [`wait_for(${label}, 'wave your hand in front of it', lambda: ${n}.motion_detected, 20, 'check OUT on ${pin}; it needs ~30 s to warm up after power-on')`] : [`wait_for(${label}, 'wave your hand in front of it', lambda: ${n}.value() == 1, 20, 'check OUT on ${pin}; it needs ~30 s to warm up after power-on')`];
    case 'ldr':
    case 'ntc':
    case 'soil': {
      const read = pi ? `${n}.value` : `${n}.read_u16() / 65535`;
      return [`v = ${read}`, `report(${label}, 0.02 < v < 0.98, 'reads %d %% of full scale' % (v * 100) if 0.02 < v < 0.98 else 'stuck at %d %%: check its wires and the divider resistor' % (v * 100))`];
    }
    case 'pot': {
      const read = pi ? `${n}.value` : `${n}.read_u16() / 65535`;
      return [`start = ${read}`, `wait_for(${label}, 'turn the knob', lambda: abs(${read} - start) > 0.2, 15, 'check the middle leg goes to ${pin} and the outer legs to 3.3 V and GND')`];
    }
    case 'button':
      return pi ? [`wait_for(${label}, 'press it', lambda: ${n}.is_pressed, 15, 'check one leg goes to ${pin} and the other to GND')`] : [`wait_for(${label}, 'press it', lambda: ${n}.value() == 0, 15, 'check one leg goes to ${pin} and the other to GND')`];
    case 'switch':
      return pi ? [`start = ${n}.is_pressed`, `wait_for(${label}, 'slide the switch', lambda: ${n}.is_pressed != start, 15, 'check the middle leg goes to ${pin}')`] : [`start = ${n}.value()`, `wait_for(${label}, 'slide the switch', lambda: ${n}.value() != start, 15, 'check the middle leg goes to ${pin}')`];
    case 'led':
      return [
        ...(pi ? [...out(`${n}.on()`, `${n}.off()`), ...out(`${n}.on()`, `${n}.off()`), ...out(`${n}.on()`, `${n}.off()`)] : ['for i in range(3):', `    ${n}.duty_u16(65535)`, '    sleep_ms(300)', `    ${n}.duty_u16(0)`, '    sleep_ms(300)']),
        `see(${label}, 'blinked 3 times (if not: turn it round, long leg towards the resistor)')`,
      ];
    case 'buzzer':
      return [
        ...(pi ? ['for i in range(3):', `    ${n}.value = 0.5`, '    sleep_ms(150)', `    ${n}.value = 0`, '    sleep_ms(150)'] : ['for i in range(3):', `    ${n}.duty_u16(32768)`, '    sleep_ms(150)', `    ${n}.duty_u16(0)`, '    sleep_ms(150)']),
        `see(${label}, 'beeped 3 times')`,
      ];
    case 'servo':
      return [
        ...(pi ? [`${n}.angle = 0`, 'sleep_ms(600)', `${n}.angle = 180`, 'sleep_ms(600)', `${n}.angle = 90`, 'sleep_ms(600)'] : ['for a in (0, 180, 90):', `    ${n}.duty_u16(int(1638 + a / 180 * (8192 - 1638)))`, '    sleep_ms(600)']),
        `see(${label}, 'swung to one end, the other end, then the middle')`,
      ];
    case 'relay':
      return [...(pi ? [`${n}.on()`, 'sleep_ms(500)', `${n}.off()`] : [`${n}.value(1)`, 'sleep_ms(500)', `${n}.value(0)`]), `see(${label}, 'clicked on and off (its LED lights while on)')`];
    case 'neopixel':
      return pi
        ? ['for c in ((40, 0, 0), (0, 40, 0), (0, 0, 40), (0, 0, 0)):', `    ${n}.fill(c)`, `    ${n}.show()`, '    sleep_ms(400)', `see(${label}, 'lit red, green, blue, then went dark')`]
        : ['for c in ((40, 0, 0), (0, 40, 0), (0, 0, 40), (0, 0, 0)):', `    ${n}.fill(c)`, `    ${n}.write()`, '    sleep_ms(400)', `see(${label}, 'lit red, green, blue, then went dark')`];
    default:
      return [];
  }
}

/** Board pin names in words that can't be mistaken for breadboard holes: ESP32 "D22" (hole d22?) → "pin D22 (GPIO22)". */
export function pinWords(pin: string | number | undefined): string {
  const s = String(pin ?? '');
  const d = /^D(\d+)$/.exec(s);
  return d ? `pin D${d[1]} (GPIO${d[1]})` : /^GP\d+$/.test(s) ? `pin ${s}` : s;
}

export interface SelfTestLine {
  kind: 'PASS' | 'FAIL' | 'ACTION' | 'LOOK' | 'INFO' | 'DONE' | 'START';
  part: string;
  text: string;
}

/** Parse self-test output (from the real board or the simulator). */
export function parseSelfTest(output: string): { lines: SelfTestLine[]; done: { passed: number; failed: number; look: number } | null } {
  const lines: SelfTestLine[] = [];
  let done: { passed: number; failed: number; look: number } | null = null;
  for (const raw of output.split(/\r?\n/)) {
    const d = /^SELFTEST DONE: (\d+) passed, (\d+) failed, (\d+) to check by eye/.exec(raw);
    if (d) {
      done = { passed: +d[1], failed: +d[2], look: +d[3] };
      lines.push({ kind: 'DONE', part: '', text: raw });
      continue;
    }
    const m = /^(PASS|FAIL|ACTION|LOOK|INFO) ([^:]+): (.*)$/.exec(raw);
    if (m) lines.push({ kind: m[1] as SelfTestLine['kind'], part: m[2], text: m[3] });
    else if (raw.startsWith('SELFTEST START')) lines.push({ kind: 'START', part: '', text: raw });
  }
  return { lines, done };
}
