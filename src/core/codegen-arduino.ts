// Arduino C++ sketch generator for boards whose firmware is a sketch (the Nicla Voice). It covers the parts the
// planner allows on those boards: buttons, switches, LEDs (switched by a transistor) and analog sensors.
// Pin numbers are the Arduino core's own (variant.cpp), taken from each board pin's `fw`.
import type { FeatureInstance, Project } from './types';
import { BOARDS, fwPin, type BoardDef } from './boards';

const ANALOG = ['pot', 'ldr', 'ntc', 'soil'];

export function generateSketch(project: Project): string {
  const board = BOARDS[project.board as Exclude<Project['board'], 'none'>];
  const fs = project.features ?? [];
  const buttons = fs.filter((f) => f.kind === 'button');
  const switches = fs.filter((f) => f.kind === 'switch');
  const leds = fs.filter((f) => f.kind === 'led');
  const sensors = fs.filter((f) => ANALOG.includes(f.kind));
  const other = fs.filter((f) => ![...buttons, ...switches, ...leds, ...sensors].includes(f));
  const C = (f: FeatureInstance) => `${f.name.toUpperCase()}_PIN`;
  const L: string[] = [];
  const add = (...ls: string[]) => L.push(...ls);

  add(`// ${project.name}`, `// Generated by Sparkbench for the ${board.name} (Arduino C++, "Arduino Mbed OS Nicla Boards" core).`, '//', '// Wiring (see the build guide for the full table):');
  for (const f of fs) add(`//   ${f.label.padEnd(26)} ${Object.entries(f.pins).map(([s, p]) => `${s === 'pin' ? '' : `${s.toUpperCase()} `}${pinText(board, p)}`).join(', ')}`);
  add('//');
  if (leds.length) add('// The header pins are low power, so each LED is switched by an NPN transistor (see the wiring).');
  if (sensors.length) add('// Analog inputs: the ADC reference is fixed to 1.8 V, so readings stop rising above 1.8 V.');
  for (const f of other) add(`// ${f.label}: Sparkbench doesn't write Arduino code for this part yet.`);
  add('', '#include "Nicla_System.h"', '');

  add('// ---- pins (Arduino pin numbers on this board) ----');
  for (const f of [...buttons, ...switches, ...leds, ...sensors]) add(`const int ${C(f)} = ${fwPin(board, f.gpio.pin)};  // ${f.label}`);
  add('');

  add('// ---- settings you can tweak ----', 'const unsigned long LOOP_MS = 20;      // main loop period', 'const unsigned long BLINK_MS = 500;    // heartbeat blink half-period');
  if (sensors.length) add('const unsigned long PRINT_MS = 1000;    // how often the readings are printed');
  if (sensors.some((f) => f.kind === 'ldr')) add('const int DARK_PCT = 30;               // %: below this light level counts as "dark"');
  if (sensors.some((f) => f.kind === 'soil')) add('const int DRY_PCT = 30;                // %: soil drier than this counts as "dry"');
  add('');

  const role = new Map([...ledRoles(fs)].map(([name, r]) => [name, r.expr]));

  add('// ---- state ----');
  for (const l of leds) if (role.get(l.name) === `${l.name}_on`) add(`bool ${l.name}_on = false;`);
  for (const b of buttons) add(`int ${b.name}_last = HIGH;`, `unsigned long ${b.name}_t = 0;`);
  for (const s of switches) add(`int ${s.name}_last = -1;`);
  for (const s of sensors) add(`int ${s.name}_pct = 0;`);
  if (sensors.length) add('unsigned long last_print = 0;');
  add('');

  if (buttons.length)
    add(
      '// True once per press (buttons pull the pin LOW; 30 ms debounce).',
      'bool pressed(int pin, int &last, unsigned long &t) {',
      '  int v = digitalRead(pin);',
      '  bool hit = false;',
      '  if (v != last && millis() - t > 30) {',
      '    t = millis();',
      '    hit = v == LOW;',
      '    last = v;',
      '  }',
      '  return hit;',
      '}',
      '',
    );
  if (sensors.length) add('// 0–100 % of the ADC range (0–1.8 V).', 'int percent(int pin) {', '  return (long)analogRead(pin) * 100 / 4095;', '}', '');

  add('void setup() {', '  nicla::begin();            // power chip on: this enables the VDDIO_EXT 3.3 V output for the header pins', '  Serial.begin(115200);');
  if (sensors.length) add('  analogReadResolution(12);  // 0–4095');
  for (const f of [...buttons, ...switches]) add(`  pinMode(${C(f)}, INPUT_PULLUP);`);
  for (const f of leds) add(`  pinMode(${C(f)}, OUTPUT);`, `  digitalWrite(${C(f)}, LOW);`);
  add(`  Serial.println("${short(project.name, 40)} starting...");`, '}', '');

  add('void loop() {', '  unsigned long now = millis();');
  for (const b of buttons) {
    const toggles = leds.filter((l, i) => buttons[i % buttons.length] === b && role.get(l.name) === `${l.name}_on`);
    add(`  if (pressed(${C(b)}, ${b.name}_last, ${b.name}_t)) {`, `    Serial.println("${short(b.label, 30)} pressed");`);
    for (const l of toggles) add(`    ${l.name}_on = !${l.name}_on;`);
    add('  }');
  }
  for (const s of switches) add(`  int ${s.name}_now = digitalRead(${C(s)});`, `  if (${s.name}_now != ${s.name}_last) {`, `    ${s.name}_last = ${s.name}_now;`, `    Serial.println(${s.name}_now == LOW ? "${short(s.label, 30)}: ON" : "${short(s.label, 30)}: off");`, '  }');
  for (const s of sensors) add(`  ${s.name}_pct = percent(${C(s)});`);
  if (sensors.length) {
    add('  if (now - last_print >= PRINT_MS) {', '    last_print = now;');
    for (const s of sensors) add(`    Serial.print("${short(s.label, 24)}: ");`, `    Serial.print(${s.name}_pct);`, '    Serial.println(" %");');
    add('  }');
  }
  for (const l of leds) {
    const r = role.get(l.name)!;
    add(`  digitalWrite(${C(l)}, ${r === 'blink' ? '(now / BLINK_MS) % 2' : r} ? HIGH : LOW);`);
  }
  add('  delay(LOOP_MS);', '}');
  return L.join('\n') + '\n';
}

/** What each LED does in the sketch: toggled by a button, else follows a sensor, else a heartbeat blink. */
function ledRoles(fs: FeatureInstance[]): Map<string, { expr: string; does: string; test: string }> {
  const buttons = fs.filter((f) => f.kind === 'button');
  const sensor = (k: string) => fs.find((s) => s.kind === k);
  const out = new Map<string, { expr: string; does: string; test: string }>();
  fs.filter((f) => f.kind === 'led').forEach((l, i) => {
    const btn = buttons.length ? buttons[i % buttons.length] : undefined;
    const ldr = sensor('ldr');
    const soil = sensor('soil');
    const pot = sensor('pot');
    if (btn) out.set(l.name, { expr: `${l.name}_on`, does: `${l.label} turns on and off each time you press ${btn.label}.`, test: `Press ${btn.label} twice: ${l.label} should come on, then go off.` });
    else if (ldr) out.set(l.name, { expr: `${ldr.name}_pct < DARK_PCT`, does: `${l.label} lights up when it gets dark.`, test: `Cover ${ldr.label}: ${l.label} should come on.` });
    else if (soil) out.set(l.name, { expr: `${soil.name}_pct < DRY_PCT`, does: `${l.label} lights up when the soil is dry.`, test: `Hold ${soil.label} in dry air: ${l.label} should come on.` });
    else if (pot) out.set(l.name, { expr: `${pot.name}_pct > 50`, does: `${l.label} is on while ${pot.label} reads above 50 %.`, test: `Turn ${pot.label} up: ${l.label} should come on past about half of the 0–1.8 V range.` });
    else out.set(l.name, { expr: 'blink', does: `${l.label} blinks steadily (half a second on, half off) to show the sketch is running.`, test: `${l.label} should blink about once a second.` });
  });
  return out;
}

/** What the generated sketch does, for the requirements card and build guide (the Python simulator can't run it). */
export function sketchBehaviour(project: Project): { does: string; test: string }[] {
  const fs = project.features ?? [];
  const out: { does: string; test: string }[] = [{ does: `When it starts, it prints "${short(project.name, 40)} starting..." over serial.`, test: 'Open the Arduino IDE Serial Monitor at 115200 baud and press reset: the message should appear.' }];
  for (const b of fs.filter((f) => f.kind === 'button')) out.push({ does: `Pressing ${b.label} prints "${short(b.label, 30)} pressed".`, test: `Press ${b.label}: the Serial Monitor should show "${short(b.label, 30)} pressed".` });
  for (const s of fs.filter((f) => f.kind === 'switch')) out.push({ does: `Flipping ${s.label} prints whether it is ON or off.`, test: `Flip ${s.label}: the Serial Monitor should show its new state.` });
  for (const s of fs.filter((f) => ANALOG.includes(f.kind))) out.push({ does: `Every second it prints ${s.label} as 0–100 % (of 0–1.8 V).`, test: `Change ${s.label}: the printed percentage should follow (it tops out at 1.8 V).` });
  for (const r of ledRoles(fs).values()) out.push({ does: r.does, test: r.test });
  return out;
}

function pinText(board: BoardDef, name: string): string {
  const p = board.pins.find((x) => x.name === name);
  return p?.header ? `${name} (pad ${p.header}) = Arduino pin ${p.fw}` : name;
}

function short(s: string, n: number) {
  return s.replace(/["\\]/g, "'").replace(/[^\x20-\x7e]/g, '').slice(0, n);
}
